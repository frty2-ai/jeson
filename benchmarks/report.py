#!/usr/bin/env python3
"""benchmarks/RESULTS.md from the result files: one table per level (every system on the same 50 test pages), the
speed table, and how each number was made.

Cost conventions: hosted rows are the providers' own usage figures at serial list price (Anthropic Batch API runs
are shown at what the same calls cost one at a time). jeson rows are serial GPU time at $0.34/h (an RTX 4090 at a
community-cloud rate; the runs were on a smaller card), so they are priced conservatively.

  python benchmarks/report.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE / "results"
GPU_H = 0.34
LEVELS = {"L1": ("Simple documents", "KYC form, invoice or statement", "9 (7-10)", "1, flat"),
          "L2": ("Invoice with line items", "10 line-item sections", "40", "2"),
          "L3": ("Bank statement", "25 transaction sections", "107", "2")}


def money(x):
    return "-" if x is None else (f"${x:.4f}" if x < 0.01 else f"${x:.3f}" if x < 1 else f"${x:.2f}")


def secs(x):
    return "-" if x is None else (f"{x * 1000:.0f} ms" if x < 1 else f"{x:.1f} s")


def gpu_cost_per_1k(ms):
    return ms / 1000 * GPU_H / 3600 * 1000


def main() -> None:
    ours = json.loads((R / "jeson-synth.json").read_text()) if (R / "jeson-synth.json").exists() else None
    speed = json.loads((R / "speed.json").read_text()) if (R / "speed.json").exists() else None
    hosted = [json.loads(p.read_text()) for p in sorted((R / "hosted").glob("*.json"))]
    out = ["# Benchmark results", "",
           "Generated by `benchmarks/report.py` from `benchmarks/results/`. Method, settings and caveats: [docs/benchmarks.md](../docs/benchmarks.md).", "",
           "Agreement is the share of typed fields (booleans, choices, ordinals) equal to the truth the page was rendered from, "
           "on the first 50 test pages of each level. **Read every row against the no-model prior**: the most frequent training value "
           "per field, answered without looking at the page. A request the provider failed (see Answered) counts as wrong.", ""]
    for lv, (title, what, fields, depth) in LEVELS.items():
        out += [f"## {lv}: {title} ({what}; {fields} fields; depth {depth})", "",
                "| System | Agreement | Answered | Valid JSON | Latency p50 | $ / 1k pages |", "|---|---|---|---|---|---|"]
        rows, excluded = [], []
        if ours and lv in ours["levels"]:
            o = ours["levels"][lv]
            n = o["n50"]
            ms = o["latency_ms_p50"]
            rows.append(("no model (prior)", n["prior"]["agreement"], "-", "-", None, None))
            rows.append(("**jeson** Reader, zero-shot", n["zero_shot"]["agreement"], "50/50", "by construction", ms["zero_shot_and_locked"] / 1000,
                         gpu_cost_per_1k(ms["zero_shot_and_locked"])))
            rows.append((f"**jeson** Reader + Lock ({o['train_pages']} pages, {o['lock_fit_s_one_thread']} s on 1 CPU thread)", n["locked"]["agreement"],
                         "50/50", "by construction", ms["zero_shot_and_locked"] / 1000, gpu_cost_per_1k(ms["zero_shot_and_locked"])))
            rows.append((f"**jeson** FastReader ({o['train_pages']} pages, {o['fast_train_gpu_s']} s training)", n["fast"]["agreement"], "50/50",
                         "by construction", ms["fast_end_to_end"] / 1000, gpu_cost_per_1k(ms["fast_end_to_end"])))
        for h in hosted:
            if h["level"] != lv:
                continue
            name = h["model"] + (" (schema in prompt, no strict mode)" if h["mode"] == "prompt_only" else "")
            answered = h["n"] - (h.get("errors") or 0)
            if h["valid_json"] == 0 and h["mode"] == "strict" and h["provider"] == "anthropic":  # batch refusals carry no error text
                excluded.append(f"{name}: every request refused by the provider's strict mode (\"compiled grammar is too large\")")
                continue
            if answered < h["n"] / 2:
                excluded.append(f"{name}: {h['n'] - answered} of {h['n']} requests failed with provider errors (HTTP 429); not a measurement of the model")
                continue
            rows.append((name, h["agreement"], f"{answered}/{h['n']}", f"{h['valid_json']}/{answered}", h["latency_s_p50"], h["usd_per_1k_serial"]))
        rows.sort(key=lambda r: -r[1])
        out += [f"| {m} | {a:.3f} | {ans} | {v} | {secs(lat)} | {money(c)} |" for m, a, ans, v, lat, c in rows]
        if excluded:
            out += ["", "Not ranked: " + "; ".join(excluded) + "."]
        out.append("")
    if speed:
        out += ["## Latency against schema size", "",
                f"Batch 1, p50 over {speed['pages']} statement pages; schemas cut from the 107-field L3 schema. GPU: {speed['gpu']}; "
                f"CPU: {speed['cpu_threads']} threads.", "",
                "| Fields | Reader (GPU) | FastReader (GPU) | FastReader (CPU) |", "|---|---|---|---|"]
        for n in speed["reader_ms"]:
            out.append(f"| {n} | {secs(speed['reader_ms'][n] / 1000)} | {secs(speed['fast_gpu_ms'][n] / 1000)} | {secs(speed['fast_cpu_ms'][n] / 1000)} |")
        out.append("")
    (HERE / "RESULTS.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
